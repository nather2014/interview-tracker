CREATE TABLE IF NOT EXISTS interview (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company VARCHAR(120) NOT NULL,
 role VARCHAR(160) NOT NULL,
 experience VARCHAR(20) NOT NULL,
 interview_type VARCHAR(30) NOT NULL,
 interview_date DATE NOT NULL,
 location VARCHAR(120) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS question (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 interview_id BIGINT NOT NULL REFERENCES interview(id) ON DELETE CASCADE,
 position INTEGER NOT NULL,
 question VARCHAR(2000) NOT NULL,
 topic VARCHAR(80) NOT NULL
);
CREATE INDEX IF NOT EXISTS question_interview_idx ON question(interview_id);
CREATE INDEX IF NOT EXISTS interview_date_idx ON interview(interview_date DESC, id DESC);
CREATE INDEX IF NOT EXISTS interview_company_idx ON interview(company);
CREATE INDEX IF NOT EXISTS question_topic_idx ON question(topic);

ALTER TABLE interview ADD COLUMN IF NOT EXISTS field VARCHAR(80) NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS interview_field_idx ON interview(lower(field));
CREATE INDEX IF NOT EXISTS interview_role_idx ON interview(lower(role));
